using System;
using System.IO;
using System.Text;
using System.Threading.Tasks;
using System.Windows.Forms;
using Microsoft.Web.WebView2.Core;
using Microsoft.Web.WebView2.WinForms;
using NebulaServer.Helpers;
using Serilog;

namespace NebulaServer.Services;

public static class YouTubeCookieService
{
    public static string CookieFilePath => Path.Combine(RuntimePaths.Data, "cookies.txt");
    public static string WebViewDataFolder => Path.Combine(RuntimePaths.Data, "WebViewProfile");

    public record CookieStatus(bool Exists, int Count, bool IsLoggedIn, DateTime? LastModified, string Path);

    public static CookieStatus GetStatus()
    {
        var path = CookieFilePath;
        if (!File.Exists(path))
            return new CookieStatus(false, 0, false, null, path);

        try
        {
            var lines = File.ReadAllLines(path);
            int count = 0;
            bool loggedIn = false;

            foreach (var line in lines)
            {
                var trimmed = line.Trim();
                if (string.IsNullOrEmpty(trimmed) || trimmed.StartsWith("#"))
                    continue;

                var parts = trimmed.Split('\t');
                if (parts.Length >= 7)
                {
                    count++;
                    var name = parts[5].Trim();
                    if (name is "LOGIN_INFO" or "SID" or "SSID" or "__Secure-3PSID" or "__Secure-1PSID" or "SAPISID")
                    {
                        loggedIn = true;
                    }
                }
            }

            var fi = new FileInfo(path);
            return new CookieStatus(count > 0, count, loggedIn, fi.LastWriteTimeUtc, path);
        }
        catch (Exception ex)
        {
            Log.Warning(ex, "Failed to read cookie status from {Path}", path);
            return new CookieStatus(false, 0, false, null, path);
        }
    }

    public static async Task SaveNetscapeCookiesAsync(string content)
    {
        RuntimePaths.EnsureDirectories();
        var tempFile = CookieFilePath + ".tmp";
        await File.WriteAllTextAsync(tempFile, content, Encoding.UTF8);
        File.Move(tempFile, CookieFilePath, overwrite: true);
        Log.Information("Saved {Length} bytes of cookies to {Path}", content.Length, CookieFilePath);
    }

    public static void DeleteCookies()
    {
        try
        {
            if (File.Exists(CookieFilePath))
                File.Delete(CookieFilePath);
            Log.Information("Deleted cookies file at {Path}", CookieFilePath);
        }
        catch (Exception ex)
        {
            Log.Warning(ex, "Failed to delete cookies file");
        }
    }

    public static async Task<bool> SaveCookiesFromManagerAsync(CoreWebView2CookieManager cookieManager)
    {
        try
        {
            var ytCookies = await cookieManager.GetCookiesAsync("https://www.youtube.com");
            var googleCookies = await cookieManager.GetCookiesAsync("https://accounts.google.com");

            var sb = new StringBuilder();
            sb.AppendLine("# Netscape HTTP Cookie File");
            sb.AppendLine("# https://curl.se/docs/http-cookies.html");
            sb.AppendLine("# This file is automatically generated by Tanzeel Media Downloader.");
            sb.AppendLine();

            int count = 0;
            var seen = new HashSet<string>(StringComparer.OrdinalIgnoreCase);

            void AppendCookie(CoreWebView2Cookie c)
            {
                var key = $"{c.Domain}|{c.Path}|{c.Name}";
                if (!seen.Add(key)) return;

                var domain = c.Domain;
                var includeSubdomains = domain.StartsWith(".") ? "TRUE" : "FALSE";
                var path = string.IsNullOrEmpty(c.Path) ? "/" : c.Path;
                var secure = c.IsSecure ? "TRUE" : "FALSE";
                long expires;
                var expiresDate = c.Expires;
                if (expiresDate <= DateTime.UnixEpoch || expiresDate == DateTime.MinValue)
                {
                    // Default session cookie expiry to 1 year ahead
                    expires = DateTimeOffset.UtcNow.AddYears(1).ToUnixTimeSeconds();
                }
                else
                {
                    expires = new DateTimeOffset(expiresDate.ToUniversalTime()).ToUnixTimeSeconds();
                }

                sb.Append(domain).Append('\t')
                  .Append(includeSubdomains).Append('\t')
                  .Append(path).Append('\t')
                  .Append(secure).Append('\t')
                  .Append(expires).Append('\t')
                  .Append(c.Name).Append('\t')
                  .AppendLine(c.Value);

                count++;
            }

            foreach (var c in ytCookies) AppendCookie(c);
            foreach (var c in googleCookies) AppendCookie(c);

            if (count > 0)
            {
                await SaveNetscapeCookiesAsync(sb.ToString());
                Log.Information("Extracted and saved {Count} cookies from WebView2", count);
                return true;
            }
            return false;
        }
        catch (Exception ex)
        {
            Log.Warning(ex, "Failed to extract cookies from WebView2");
            return false;
        }
    }

    public static void ShowLoginWindow(IWin32Window? owner, Action<bool, string>? onCompleted = null)
    {
        var form = new Form
        {
            Text = "YouTube Login & Auto-Cookie Sync — Tanzeel",
            Width = 900,
            Height = 720,
            StartPosition = FormStartPosition.CenterScreen,
            ShowIcon = true,
            FormBorderStyle = FormBorderStyle.Sizable,
            MinimizeBox = false,
            MaximizeBox = true
        };

        var statusStrip = new StatusStrip();
        var statusLabel = new ToolStripStatusLabel
        {
            Text = "Loading YouTube login… Please sign in to your Google / YouTube account.",
            Spring = true,
            TextAlign = System.Drawing.ContentAlignment.MiddleLeft
        };
        statusStrip.Items.Add(statusLabel);

        var webView = new WebView2
        {
            Dock = DockStyle.Fill
        };

        form.Controls.Add(webView);
        form.Controls.Add(statusStrip);

        bool completed = false;

        form.Shown += async (_, _) =>
        {
            try
            {
                Directory.CreateDirectory(WebViewDataFolder);
                var env = await CoreWebView2Environment.CreateAsync(null, WebViewDataFolder);
                await webView.EnsureCoreWebView2Async(env);

                statusLabel.Text = "Navigate and sign in to YouTube. Once signed in, cookies will sync automatically.";

                webView.NavigationCompleted += async (_, e) =>
                {
                    if (!e.IsSuccess || completed) return;

                    var uri = webView.Source;
                    if (uri == null) return;

                    var url = uri.ToString();
                    if (url.Contains("youtube.com", StringComparison.OrdinalIgnoreCase))
                    {
                        var manager = webView.CoreWebView2.CookieManager;
                        var cookies = await manager.GetCookiesAsync("https://www.youtube.com");
                        bool hasAuth = false;
                        foreach (var c in cookies)
                        {
                            if (c.Name is "LOGIN_INFO" or "SID" or "SSID" or "__Secure-3PSID" or "__Secure-1PSID")
                            {
                                hasAuth = true;
                                break;
                            }
                        }

                        if (hasAuth)
                        {
                            completed = true;
                            statusLabel.Text = "✓ Authentication detected! Saving cookies…";
                            statusLabel.ForeColor = System.Drawing.Color.Green;

                            var saved = await SaveCookiesFromManagerAsync(manager);
                            if (saved)
                            {
                                statusLabel.Text = "✓ YouTube cookies saved successfully! You can close this window.";
                                await Task.Delay(1200);
                                if (!form.IsDisposed)
                                {
                                    form.Close();
                                }
                                onCompleted?.Invoke(true, "Cookies synced successfully.");
                            }
                        }
                    }
                };

                // Navigate to YouTube login
                webView.CoreWebView2.Navigate("https://accounts.google.com/ServiceLogin?service=youtube&continue=https%3A%2F%2Fwww.youtube.com%2F");
            }
            catch (Exception ex)
            {
                Log.Error(ex, "Failed to initialize WebView2 in login window");
                statusLabel.Text = "Error: " + ex.Message;
                statusLabel.ForeColor = System.Drawing.Color.Red;
            }
        };

        form.FormClosed += (_, _) =>
        {
            if (!completed)
            {
                onCompleted?.Invoke(false, "Login window was closed before sign-in completed.");
            }
        };

        if (owner != null)
            form.Show(owner);
        else
            form.Show();
    }
}
